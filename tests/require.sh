#!/usr/bin/env bash
# require.sh — общая проверка зависимостей для тестов.
#
# Без неё отсутствие jq превращалось в сорок строк «command not found» вперемешку
# с FAIL, и человек читал это как «проверки провалились», а не как «нечем
# проверять». Разница существенная: в первом случае чинят репозиторий,
# во втором — ставят одну программу.
#
# Молча пропускать шаг нельзя: пропущенная проверка выглядит как пройденная.
# Поэтому не skip, а внятная остановка с ненулевым кодом.
#
# Подключение:  . "$(dirname "${BASH_SOURCE[0]}")/require.sh"; require_tools jq git

# Кириллица в сравнениях: grep -i приводит регистр только для ASCII, если
# локаль однобайтовая. На чужой машине с LANG=C проверка «в тексте есть слово»
# молча не срабатывала. Задаём локаль сами — тесты обязаны идти одинаково везде.
if [[ -z "${LC_ALL:-}" ]]; then
  if locale -a 2>/dev/null | grep -qi '^C\.utf-\?8$'; then
    export LC_ALL=C.UTF-8
  elif locale -a 2>/dev/null | grep -qi '^en_US\.utf-\?8$'; then
    export LC_ALL=en_US.UTF-8
  fi
  # Локали может не быть вовсе — тогда сравнения с кириллицей всё равно обязаны
  # работать, поэтому в самих тестах регистр не приводится: ищется то, что
  # написано в проверяемом тексте, буква в букву.
fi
export LC_NUMERIC=C   # число с точкой: разбор вывода не должен зависеть от локали

require_tools() { # <программа>...
  local missing=() t
  for t in "$@"; do
    command -v "$t" >/dev/null 2>&1 || missing+=("$t")
  done
  [[ ${#missing[@]} -eq 0 ]] && return 0

  printf '\033[31mПрогон невозможен\033[0m: не найдено — %s\n' "${missing[*]}" >&2
  printf 'Это не провал проверок, а отсутствие инструмента. Поставь и повтори:\n' >&2
  printf '  Debian/Ubuntu:  sudo apt install %s\n' "${missing[*]}" >&2
  printf '  macOS:          brew install %s\n' "${missing[*]}" >&2
  printf '  Fedora:         sudo dnf install %s\n' "${missing[*]}" >&2
  exit 2
}
